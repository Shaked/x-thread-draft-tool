#!/usr/bin/env node
// Lints one GitHub comment written by an agent for the owner. A comment is checked when it ends with the Claude Code
// footer and starts with HANDOFF, "Decision" (word rules only, no headings required), a question (the first line
// ends with "?") or the template heading "## TL;DR" (an owner question or status report written with the template).
// Other comments are skipped (exit 0).
// Usage: COMMENT_BODY=... node scripts/reply-lint-comment.mjs [--config <file>]   (or the body on stdin)
// Exits 1 and prints `line N: rule: message` when an agent comment breaks the reply-style rules, 2 on a broken config.
import { readFileSync } from 'node:fs'
import { pathToFileURL } from 'node:url'
import { ConfigError, loadConfig } from './config.mjs'
import { DEFAULT_CONFIG, lint } from './reply-lint.mjs'

const FOOTER = /_Generated by \[Claude Code\]\(https:\/\/claude\.ai\/code\)_\s*$/

/** The kind of agent comment: 'handoff', 'decision', 'question', 'templated', or null when the lint does not apply. */
export function agentCommentKind(body) {
  const text = String(body || '').trim()
  if (!FOOTER.test(text)) return null
  const first = text.split('\n').find((l) => l.trim()) || ''
  if (/^HANDOFF\b/.test(first)) return 'handoff'
  if (/^Decision\b/.test(first)) return 'decision'
  if (/^##\s+TL;DR\s*$/.test(first.trim())) return 'templated'
  if (/\?\s*$/.test(first.trim())) return 'question'
  return null
}

/** Findings for one comment ([] when it is not an agent comment or passes). */
export function lintComment(body, config = DEFAULT_CONFIG) {
  const kind = agentCommentKind(body)
  if (!kind) return []
  // A Decision record is a short dated line, not a report: the word rules apply, the headings only when it has any.
  return lint(String(body), { template: kind !== 'decision' }, config)
}

function main() {
  const body = process.env.COMMENT_BODY ?? readFileSync(0, 'utf8')
  const kind = agentCommentKind(body)
  if (!kind) {
    console.log('reply-lint-comment: not an agent comment for the owner, skipped')
    return
  }
  const configAt = process.argv.indexOf('--config')
  let config
  try {
    config = loadConfig({ file: configAt === -1 ? undefined : process.argv[configAt + 1] })
  } catch (error) {
    if (!(error instanceof ConfigError)) throw error
    console.error(error.message)
    process.exit(2)
  }
  const findings = lintComment(body, config)
  for (const f of findings) console.log(`line ${f.line}: ${f.rule}: ${f.message}`)
  console.log(findings.length ? `reply-lint-comment: ${kind}: ${findings.length} finding(s)` : `reply-lint-comment: ${kind}: OK`)
  if (findings.length) process.exit(1)
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main()
