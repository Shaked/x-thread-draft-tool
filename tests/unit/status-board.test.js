// @vitest-environment node
import { describe, it, expect } from 'vitest'
import { readFileSync } from 'node:fs'
import { spawnSync } from 'node:child_process'
import { boardNeeds, buildBoard, formatBoard, GROUPS, isOwnerQuestion, manualTests, OWNER_RULES, ownerNeeded, prIssue, section } from '../../scripts/status-board.mjs'
import { lint } from '../../scripts/reply-lint.mjs'

const dir = new URL('./fixtures/status-board/', import.meta.url)
const load = (name) => JSON.parse(readFileSync(new URL(name, dir), 'utf8'))
const sessions = load('sessions.json')
const snapshot = load('snapshot.json')
const comments = load('comments.json')
const pulls = load('pulls.json')
const board = buildBoard(sessions, snapshot, { comments, pulls })
const text = formatBoard(board)
const GOLDEN = new URL('./fixtures/reply-lint/golden/status-board/good-1.md', import.meta.url)
const group = (g) => board.rows.filter((r) => r.group === g).map((r) => r.issue)
const FOOTER = '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_'

describe('golden board', () => {
  it('matches the golden fixture byte for byte and passes reply-lint', () => {
    expect(text).toBe(readFileSync(GOLDEN, 'utf8'))
    expect(lint(text, { template: true })).toEqual([])
  })

  it('the CLI prints the same board', () => {
    const f = (n) => new URL(n, dir).pathname
    const out = spawnSync('node', ['scripts/status-board.mjs', 'board', f('sessions.json'), f('snapshot.json'), '--comments', f('comments.json'), '--pulls', f('pulls.json')], { encoding: 'utf8' })
    expect(out.status).toBe(0)
    expect(out.stdout).toBe(text)
  })

  it('every row has a ticket link and a session cell', () => {
    for (const line of text.split('\n').filter((l) => /^\| \[#\d+/.test(l))) {
      const cells = line.split(' | ')
      expect(cells[0]).toMatch(/^\| \[#\d+[^\]]*\]\(https:\/\/github\.com\//)
      expect(cells[2]).toMatch(/^(none|\[session\]\(https:\/\/claude\.ai\/code\/session_\w+\) `[a-z ]+`)/)
    }
  })
})

describe('every group has a fixture row', () => {
  const want = { 'needs-you': [301, 302, 303, 304], stuck: [306], running: [307], waiting: [308, 309], held: [310, 311], done: [312] }
  for (const [g] of GROUPS) it(g, () => expect(group(g)).toEqual(want[g]))

  it('a done row older than 24 hours drops out; an answered question and an idle task are not listed', () => {
    expect(board.rows.map((r) => r.issue)).not.toContain(313)
    expect(board.rows.map((r) => r.issue)).not.toContain(305)
    expect(board.rows.map((r) => r.issue)).not.toContain(314)
    expect(board.offBoard).toBe(2)
  })

  it('--since narrows the done rows to the time after the last board', () => {
    const later = buildBoard(sessions, snapshot, { comments, pulls, since: '2026-11-26T11:00:00Z' })
    expect(later.rows.filter((r) => r.group === 'done')).toEqual([])
    expect(formatBoard(later)).toContain('- No pull request merged since the last board, checked.')
  })

  it('epics and trackers are one line each, never rows', () => {
    expect(board.rows.map((r) => r.issue)).not.toContain(300)
    expect(board.rows.map((r) => r.issue)).not.toContain(430)
    expect(board.epics.map((e) => [e.number, e.kind])).toEqual([[300, 'epic'], [430, 'tracker']])
  })
})

describe('owner needed: each rule has a fixture', () => {
  const rules = new Map(board.rows.flatMap((r) => r.owner.map((o) => [o.rule, r.issue])))
  for (const [rule] of OWNER_RULES) it(rule, () => expect(rules.has(rule)).toBe(true))

  it('takes the exact words from the comment', () => {
    const [q] = board.rows.find((r) => r.issue === 301).owner
    expect(q).toMatchObject({ rule: 'question', what: 'should drafts save on every keystroke', words: 'save-each' })
    expect(board.rows.find((r) => r.issue === 303).owner[0]).toMatchObject({ rule: 'handoff', words: 'oauth-done' })
  })

  it('a human reply after the question or HANDOFF answers it', () => {
    const list = comments[303]
    expect(ownerNeeded({ labels: [] }, [...list, { user: 'owner', author_association: 'OWNER', created_at: '2026-11-26T11:00:00Z', body: 'done' }], [], { owner: 'owner', url: 'u' })).toEqual([])
    // An agent comment after it is not an answer.
    expect(ownerNeeded({ labels: [] }, [...list, { user: 'owner', author_association: 'OWNER', created_at: '2026-11-26T11:00:00Z', body: `note${FOOTER}` }], [], { owner: 'owner', url: 'u' })).toHaveLength(1)
  })

  it('a later decision record that names the question id or its exact words answers it', () => {
    const list = comments[301]
    const rec = (body) => ({ user: 'owner', author_association: 'OWNER', created_at: '2026-11-26T11:00:00Z', body: `${body}${FOOTER}` })
    expect(ownerNeeded({ labels: [] }, [...list, rec('Owner decision, 2026-11-26 (Shaked): `save-each`.')], [], { owner: 'owner', url: 'u' })).toEqual([])
    // A decision record about something else, or a note that names the words, does not answer it.
    expect(ownerNeeded({ labels: [] }, [...list, rec('Owner decision, 2026-11-26 (Shaked): keep the theme.')], [], { owner: 'owner', url: 'u' })).toHaveLength(1)
    expect(ownerNeeded({ labels: [] }, [...list, rec('Note: someone may reply `save-each`.')], [], { owner: 'owner', url: 'u' })).toHaveLength(1)
  })

  it('a HANDOFF with "Blocked on you: Nothing." needs nothing; parked owner tasks are Held, not Needs you', () => {
    const body = `HANDOFF B3 (x y z) - done\n\n## Blocked on you\nNothing.\n\nRELEASE${FOOTER}`
    expect(ownerNeeded({ labels: [] }, [{ user: 'owner', author_association: 'OWNER', created_at: 't', body }], [], { owner: 'owner', url: 'u' })).toEqual([])
    expect(ownerNeeded({ labels: ['owner', 'parked'] }, [], [], { owner: 'owner', url: 'u' })).toEqual([])
  })

  it('needs_action counts only when it names a decision and the session is not done or working', () => {
    const s = (bucket, needs) => ({ id: 'session_x', bucket, needs, updatedAt: '2026-11-26T10:00:00Z' })
    expect(ownerNeeded({ labels: [] }, [], [s('blocked', 'run npm ci again')], { owner: 'o', url: 'u' })).toEqual([])
    expect(ownerNeeded({ labels: [] }, [], [s('completed', 'decide the ranking')], { owner: 'o', url: 'u' })).toEqual([])
    expect(ownerNeeded({ labels: [] }, [], [s('blocked', 'decide the ranking')], { owner: 'o', url: 'u' })[0].rule).toBe('needs-action')
  })

  it('an owner question is an agent comment: a human question is not one', () => {
    expect(isOwnerQuestion({ body: 'Should we ship?' })).toBe(false)
    expect(isOwnerQuestion({ body: `Should we ship?${FOOTER}` })).toBe(true)
    expect(isOwnerQuestion({ body: `HANDOFF A1 (a b c) - done${FOOTER}` })).toBe(false)
  })
})

describe('Opus review findings on #503', () => {
  const opts = { owner: 'o', url: 'u' }
  const s = (bucket, needs) => ({ id: 'session_x', bucket, needs, updatedAt: '2026-11-26T10:00:00Z' })

  it('a decision word is not enough: "owner" or a bare "pick" names no decision', () => {
    expect(ownerNeeded({ labels: [] }, [], [s('review_ready', 'Nothing for the owner; waits for Opus review')], opts)).toEqual([])
    expect(ownerNeeded({ labels: [] }, [], [s('blocked', 'dispatcher should pick up the retry')], opts)).toEqual([])
    expect(ownerNeeded({ labels: [] }, [], [s('blocked', 'choose the font: serif or sans')], opts)).toHaveLength(1)
  })

  it('a session question older than the stale window is left to the janitor', () => {
    const fresh = { ...opts, freshFrom: Date.parse('2026-11-23T12:00:00Z') }
    expect(ownerNeeded({ labels: [] }, [], [{ ...s('blocked', 'decide the ranking'), updatedAt: '2026-11-19T05:00:00Z' }], fresh)).toEqual([])
    expect(ownerNeeded({ labels: [] }, [], [s('blocked', 'decide the ranking')], fresh)).toHaveLength(1)
  })

  it('a session with no issue that asks for a decision is in Needs you', () => {
    const extra = { id: 'session_font', title: 'Pick a font', status: 'idle', status_bucket: 'blocked', post_turn_summary: { needs_action: 'decide which font to ship' },
      updated_at: '2026-11-26T11:00:00Z', created_at: '2026-11-26T10:00:00Z', parent: 'session_disp', tags: ['pipeline'], model: null }
    const b = buildBoard({ ...sessions, sessions: [...sessions.sessions, extra] }, snapshot, { comments, pulls })
    const r = b.rows.find((x) => x.key === 's:session_font')
    expect(r).toMatchObject({ group: 'needs-you', issue: null })
    expect(lint(formatBoard(b), { template: true })).toEqual([])
  })

  it('an owner question on a tracker issue is in Needs you; the tracker stays one line too', () => {
    const tracker = { number: 154, title: 'Queue: what the agents do next', state: 'open', labels: [{ name: 'dispatch' }], body: '', updated_at: '2026-11-26T10:00:00Z' }
    const b = buildBoard(sessions, { ...snapshot, issues: [...snapshot.issues, tracker] }, { comments: { ...comments, 154: comments[301] }, pulls })
    expect(b.rows.find((x) => x.issue === 154)).toMatchObject({ group: 'needs-you', ticket: '{#154} (tracker)' })
    expect(b.epics.map((e) => e.number)).toContain(154)
  })

  it('a manual test title is quoted: a token is masked and a bracket does not break the link', () => {
    const body = `${snapshot.issues.at(-1).body}\n\n## 3. Sign-in blocked after ghp_abcdefghijklmnopqrstuvwxyz0123 rotation [beta]`
    const issues = snapshot.issues.map((i) => (i.number === 430 ? { ...i, body } : i))
    const out = formatBoard(buildBoard(sessions, { ...snapshot, issues }, { comments, pulls }))
    expect(out).not.toContain('ghp_abcdefghijklmnopqrstuvwxyz0123')
    expect(lint(out, { template: true })).toEqual([])
  })

  it('a comment with the pull request footer is an agent comment, not an answer from Shaked', () => {
    const late = { user: 'owner', author_association: 'OWNER', created_at: '2026-11-26T11:00:00Z', body: 'Note.\n\nGenerated with [Claude Code](https://claude.com/claude-code)' }
    expect(ownerNeeded({ labels: [] }, [...comments[301], late], [], { owner: 'example', url: 'u' })).toHaveLength(1)
  })

  it('a collaborator comment does not answer an owner question (Codex finding on #503)', () => {
    const late = { user: 'helper', author_association: 'COLLABORATOR', created_at: '2026-11-26T11:00:00Z', body: 'CI is green now.' }
    expect(ownerNeeded({ labels: [] }, [...comments[301], late], [], { owner: 'example', url: 'u' })).toHaveLength(1)
  })
})

describe('manual tests are optional', () => {
  it('lists the unanswered test, drops the answered one, and never counts it as owner needed', () => {
    expect(board.manual.map((t) => t.title)).toEqual(['Phone: bottom bar spacing'])
    expect(text).toContain('### Manual tests (optional, nothing waits)')
    expect(board.rows.some((r) => r.issue === 430)).toBe(false)
    expect(text.split('## Waiting for')[0]).not.toContain('Phone: bottom bar spacing')
  })

  it('reads tests from agent comments on the issue too', () => {
    const list = [{ user: 'owner', author_association: 'OWNER', created_at: '2026-11-26T09:00:00Z', body: `## 3. Editor: live update (task #363)\nReply \`ok\`.${FOOTER}`, html_url: 'c' }]
    expect(manualTests({ body: '', created_at: 't' }, list, { owner: 'owner', url: 'u' })).toEqual([{ title: 'Editor: live update', at: '2026-11-26T09:00:00Z', url: 'c' }])
  })
})

describe('helpers', () => {
  it('reads a "## " section without its template hints', () => {
    expect(section('## Blocked on you\n<Or "Nothing.">\n- Create the app.\n## Done\n- x', 'Blocked on you')).toEqual(['- Create the app.'])
  })

  it('picks one issue per PR: the title first, then Implements or Closes, then the first number', () => {
    const isIssue = (n) => [1, 2, 3].includes(n)
    expect(prIssue({ title: 'Fix (#2)', body: 'Closes #1' }, isIssue)).toBe(2)
    expect(prIssue({ title: 'Fix', body: 'See #3. Closes #1' }, isIssue)).toBe(1)
    expect(prIssue({ title: 'Fix', body: 'See #9 and #3' }, isIssue)).toBe(3)
    expect(prIssue({ title: 'Fix', body: '' }, isIssue)).toBe(null)
  })

  it('need lists the issues and PRs still to read', () => {
    const n = boardNeeds(sessions, snapshot, { comments: {}, pulls: {} })
    expect(n.issues).toEqual(expect.arrayContaining([300, 301, 303, 430]))
    expect(n.prs).toEqual([408, 409])
    expect(boardNeeds(sessions, snapshot, { comments, pulls }).prs).toEqual([])
  })

  it('need asks for the comments of every open issue that has one, so any owner question is found (Codex finding on #503)', () => {
    // #314 has no session, PR or label; its only comment is an agent question in the "?" form.
    const issues = snapshot.issues.map((i) => ({ ...i, comments: i.number === 314 ? 1 : 0 }))
    const snap = { ...snapshot, issues }
    expect(boardNeeds(sessions, snap, { comments: {}, pulls }).issues).toContain(314)
    expect(boardNeeds(sessions, snap, { comments: {}, pulls }).issues).not.toContain(305)
    const q = { user: 'example', author_association: 'OWNER', created_at: '2026-11-26T09:00:00Z', body: `Should print view use A4?\n\nReply \`a4\` or \`letter\`.${FOOTER}` }
    const b = buildBoard(sessions, snap, { comments: { ...comments, 314: [q] }, pulls })
    expect(b.rows.find((r) => r.issue === 314)).toMatchObject({ group: 'needs-you' })
  })

  it('masks a token a session wrote in its question', () => {
    const doc = { ...sessions, sessions: sessions.sessions.map((s) => (s.id === 'session_asks' ? { ...s, post_turn_summary: { needs_action: 'decide; token ghp_abcdefghijklmnopqrstuvwxyz0123' } } : s)) }
    const out = formatBoard(buildBoard(doc, snapshot, { comments, pulls }))
    expect(out).not.toContain('ghp_abcdefghijklmnopqrstuvwxyz0123')
    expect(out).toContain('[redacted]')
  })
})
