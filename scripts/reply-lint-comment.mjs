#!/usr/bin/env node
// Lints one GitHub comment written by an agent (#486). Used by .github/workflows/reply-lint-comments.yml.
// A comment is an agent comment for the owner when it ends with the Claude Code footer and starts with HANDOFF,
// "Decision", or a question (the first line ends with "?"). Other comments are skipped (exit 0).
// Usage: COMMENT_BODY=... node scripts/reply-lint-comment.mjs   (or the body on stdin)
// Exits 1 and prints `line N: rule: message` when an agent comment breaks the reply-style rules.
import { readFileSync } from 'node:fs'
import { pathToFileURL } from 'node:url'
import { lint } from './reply-lint.mjs'

const FOOTER = /_Generated by \[Claude Code\]\(https:\/\/claude\.ai\/code\)_\s*$/

/** The kind of agent comment: 'handoff', 'decision', 'question', or null when the lint does not apply. */
export function agentCommentKind(body) {
  const text = String(body || '').trim()
  if (!FOOTER.test(text)) return null
  const first = text.split('\n').find((l) => l.trim()) || ''
  if (/^HANDOFF\b/.test(first)) return 'handoff'
  if (/^Decision\b/.test(first)) return 'decision'
  if (/\?\s*$/.test(first.trim())) return 'question'
  return null
}

/** Findings for one comment ([] when it is not an agent comment or passes). */
export function lintComment(body) {
  return agentCommentKind(body) ? lint(String(body), { template: true }) : []
}

function main() {
  const body = process.env.COMMENT_BODY ?? readFileSync(0, 'utf8')
  const kind = agentCommentKind(body)
  if (!kind) {
    console.log('reply-lint-comment: not an agent comment for the owner, skipped')
    return
  }
  const findings = lintComment(body)
  for (const f of findings) console.log(`line ${f.line}: ${f.rule}: ${f.message}`)
  console.log(findings.length ? `reply-lint-comment: ${kind}: ${findings.length} finding(s)` : `reply-lint-comment: ${kind}: OK`)
  if (findings.length) process.exit(1)
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main()
