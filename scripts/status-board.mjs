#!/usr/bin/env node
// Status board (#499): tickets, pull requests and Claude sessions on one page, and whether the owner is needed.
// Node 20, no dependencies, no model, no network. It never writes anywhere. It reads the janitor's files
// (sessions.json, the pass 1 snapshot, comments.json, pulls.json) and reuses the janitor's matching of sessions
// with issues (scripts/session-janitor.mjs). Template: .claude/skills/reply-style/templates/status-board.md.
// Command: .claude/commands/status.md (/status).
//
//   node scripts/status-board.mjs fetch > snapshot.json
//       The janitor's snapshot (`janitor.mjs fetch`, gh search only), plus `markers.question`: open issues with a comment
//       that says "question for you" (an owner question in the reply template).
//   node scripts/status-board.mjs need sessions.json snapshot.json [--comments f] [--pulls f] [--today ISO] [--since ISO]
//       Prints the issues whose comments the board still needs, and the open PRs whose checks it needs.
//   node scripts/status-board.mjs board sessions.json snapshot.json [--comments f] [--pulls f] [--today ISO] [--since ISO]
//       Prints the board in the template. --since is the time of the last board (default: 24 hours before --today).
//
// buildBoard() and formatBoard() are pure: the tests run them on golden fixtures.

import { execFileSync } from 'node:child_process'
import { readFileSync } from 'node:fs'
import { pathToFileURL } from 'node:url'
import { dependencies, fetchSnapshot, REPO, shortName, TRUSTED } from './janitor.mjs'
import { analyzeSessions, context, needs as sessionNeeds, quote, validateSessions } from './session-janitor.mjs'

// The manual tests issue: its tests are listed as optional and never make the board red.
export const MANUAL_TESTS = 430
// Done rows older than this drop out.
export const DONE_HOURS = 24
// Groups in board order. The lint keeps "blocked" for a human, so the issue's "Blocked" group is "Stuck" here.
export const GROUPS = [
  ['needs-you', 'Needs you'],
  ['stuck', 'Stuck: failed, waits for an answer, or a dispatcher step'],
  ['running', 'Running'],
  ['waiting', 'Waiting for CI or review'],
  ['held', 'Held'],
  ['done', 'Done since the last board']
]
// Every "owner needed" rule. A test fails when a rule has no fixture.
export const OWNER_RULES = [
  ['question', 'an open owner question'],
  ['label', 'label `owner`'],
  ['handoff', 'the last HANDOFF names a step for you'],
  ['needs-action', 'a session asks for a decision']
]
const FOOTER = /_Generated by \[Claude Code\]\(https:\/\/claude\.ai\/code\)_\s*$/
const TRACKERS = new Set(['dispatch', 'janitor', 'tracker'])
// A needs_action names a decision when it has one of these words.
const DECISION = /\b(decide|decision|choose|pick|approve|approval|your call|which option|owner)\b/i
const STATE = { working: 'running', review_ready: 'review ready', blocked: 'blocked', failed: 'failed', completed: 'completed' }
// Janitor findings that become the next step of a row, first one wins.
const NEXT = ['stuck', 'orphan-claim', 'done-open', 'no-handoff', 'duplicate-session', 'nudge-merge', 'orphan-session', 'stale']
const DISPATCHER_STEP = new Set(['orphan-claim', 'done-open', 'no-handoff', 'duplicate-session'])
const code = (s) => `\`${s}\``
const plural = (n, one, many) => `${n} ${n === 1 ? one : many}`
const labelsOf = (i) => (i.labels || []).map((l) => (typeof l === 'string' ? l : l.name))

/** "## Name" section of a comment body: its lines up to the next "## " heading, empty lines and template hints left out. */
export function section(body, name) {
  const lines = String(body || '').split('\n')
  const at = lines.findIndex((l) => l.trim().toLowerCase() === `## ${name}`.toLowerCase())
  if (at === -1) return []
  const end = lines.findIndex((l, k) => k > at && /^##\s/.test(l))
  return lines.slice(at + 1, end === -1 ? undefined : end).map((l) => l.trim()).filter((l) => l && !/^<.*>$/.test(l) && !FOOTER.test(l) && l !== '---' && l !== 'RELEASE')
}

const isAgent = (c) => FOOTER.test(String(c.body || '').trim())
const isHuman = (c, owner) => !isAgent(c) && (TRUSTED.has(c.author_association) || c.user === owner || c.user?.login === owner)
const sorted = (list = []) => [...list].sort((a, b) => String(a.created_at).localeCompare(String(b.created_at)))
const answered = (list, at, owner) => list.some((c) => isHuman(c, owner) && String(c.created_at) > String(at))
// An agent comment that records what Shaked decided: "Owner decision, 2026-11-25 (Shaked): ...", "DECISION by Shaked".
const DECISION_RECORD = /^(?:\*\*)?(?:owner decisions?|decisions?|dispatcher decision)\b/i
const recorded = (list, at, keys) => list.some((c) => isAgent(c) && String(c.created_at) > String(at)
  && DECISION_RECORD.test(String(c.body || '').trim()) && keys.some((k) => k && k.length >= 4 && String(c.body).includes(k)))
const nothing = (lines) => !lines.length || /^nothing\b/i.test(lines.join(' '))
// The exact words to type: the first code span under "What you need to do", or after "reply".
const wordsIn = (body) => {
  const step = section(body, 'What you need to do').join(' ')
  return (/`([^`]+)`/.exec(step) || /\breply\b[^`\n]*`([^`]+)`/i.exec(String(body || '')))?.[1] ?? null
}

/** An agent comment that asks the owner: its first line ends with "?", or its TL;DR starts with "One question for you". */
export function isOwnerQuestion(c) {
  if (!isAgent(c)) return false
  const first = String(c.body || '').split('\n').find((l) => l.trim())?.trim() || ''
  const tldr = section(c.body, 'TL;DR')[0] || ''
  return /\?$/.test(first) || /^(owner question|question for shaked)\b/i.test(first) || /^(one|two|three|four|five|\d+) questions? for you\b/i.test(tldr)
}

/** The "owner needed" rules for one open issue and its sessions: [{ rule, what, words, url }]. Empty means no. */
export function ownerNeeded(issue, list = [], sessions = [], { owner, url }) {
  const out = []
  const labels = labelsOf(issue)
  for (const c of sorted(list).filter(isOwnerQuestion)) {
    const tldr = section(c.body, 'TL;DR')[0] || String(c.body).split('\n')[0]
    // The question id, as in "One question for you ([H1-Q1 how long history is kept](...))".
    const id = /questions? for you\s*\(\[([A-Z][\w-]*\d)\b/i.exec(tldr)?.[1] || null
    if (answered(list, c.created_at, owner) || recorded(list, c.created_at, [id, wordsIn(c.body)])) continue
    out.push({ rule: 'question', what: tldr.replace(/^.*?questions? for you\s*(?:\(\[([^\]]*)\]\([^)]*\)\))?:?\s*/i, (m, t) => (t ? `${t}: ` : '')).replace(/[.?]$/, ''), words: wordsIn(c.body), url: c.html_url || url })
  }
  if (labels.includes('owner') && !labels.includes('parked')) out.push({ rule: 'label', what: 'labelled `owner`: read the issue for the step', words: null, url })
  const handoffs = sorted(list).filter((c) => /^HANDOFF\b/.test(String(c.body || '')) && (TRUSTED.has(c.author_association) || c.user === owner))
  const last = handoffs[handoffs.length - 1]
  if (last && !answered(list, last.created_at, owner)) {
    const blocked = section(last.body, 'Blocked on you')
    if (!nothing(blocked)) out.push({ rule: 'handoff', what: blocked[0].replace(/^[-*]\s+/, '').replace(/\.$/, ''), words: wordsIn(last.body), url: last.html_url || url })
  }
  for (const s of sessions) {
    if (['completed', 'working'].includes(s.bucket) || !DECISION.test(s.needs)) continue
    out.push({ rule: 'needs-action', what: s.needs, words: null, url: sessionUrl(s.id) })
  }
  return out
}

/** Manual tests: each "## N. title" in the manual tests issue or an agent comment on it, with no human reply that names it. */
export function manualTests(issue, list = [], { owner, url }) {
  if (!issue) return []
  const tests = []
  const add = (body, at, link) => {
    for (const m of String(body || '').matchAll(/^##\s+\d+\.\s+(.+)$/gm)) tests.push({ title: m[1].trim(), at, url: link })
  }
  add(issue.body, issue.created_at, url)
  for (const c of sorted(list).filter(isAgent)) add(c.body, c.created_at, c.html_url || url)
  const plain = (t) => t.replace(/\s*\([^)]*#\d+[^)]*\)/g, '').replace(/#\d+/g, '').trim()
  return tests.map((t) => ({ ...t, title: plain(t.title) }))
    .filter((t) => !list.some((c) => isHuman(c, owner) && String(c.created_at) > String(t.at) && String(c.body).toLowerCase().includes(t.title.toLowerCase())))
}

export const sessionUrl = (id) => `https://claude.ai/code/${id}`

/** The one issue a PR is for: a "#n" in its title, else "Closes", "Fixes", "Resolves" or "Implements #n" in its body, else the first "#n". */
export function prIssue(p, isIssue) {
  const pick = (re, text) => [...String(text || '').matchAll(re)].map((m) => Number(m[1])).find(isIssue) ?? null
  return pick(/#(\d+)\b/g, p.title) ?? pick(/\b(?:closes|fixes|resolves|implements)\s+#(\d+)\b/gi, p.body) ?? pick(/#(\d+)\b/g, p.body)
}

/** The facts every part of the board reads: times, matching (janitor pass 2), findings, issue kinds. */
function facts(sessionsDoc, snapshot, { comments = {}, pulls = {}, today, since } = {}) {
  const now = Date.parse(today || sessionsDoc.read_at)
  if (Number.isNaN(now)) throw new Error(`not an ISO time: ${today || sessionsDoc.read_at}`)
  const from = Math.max(since ? Date.parse(since) : -Infinity, now - DONE_HOURS * 3600000)
  const repo = String(snapshot.repo || REPO)
  const c = context(sessionsDoc, snapshot, comments)
  const raw = new Map((snapshot.issues || []).map((i) => [i.number, i]))
  return {
    now,
    repo,
    c,
    raw,
    pulls,
    owner: repo.split('/')[0],
    findings: analyzeSessions(sessionsDoc, snapshot, { today: new Date(now).toISOString(), comments, pulls }),
    byId: new Map(c.workers.map((s) => [s.id, s])),
    recent: (t) => Boolean(t) && Date.parse(t) >= from && Date.parse(t) <= now,
    url: (n) => raw.get(n)?.html_url || `https://github.com/${repo}/issues/${n}`,
    kind: (n) => issueKind(n, raw.get(n)),
    isOpen: (n) => c.byNum.get(n)?.state === 'open',
    isIssue: (n) => c.byNum.has(n)
  }
}

function issueKind(n, issue) {
  const labels = labelsOf(issue || {})
  if (labels.includes('epic')) return 'epic'
  return labels.some((l) => TRACKERS.has(l)) || n === MANUAL_TESTS ? 'tracker' : 'ticket'
}

/** One work item per issue (or per session or PR with no issue): its sessions, open PRs and PRs merged in the window. */
function collect(x, snapshot) {
  const items = new Map()
  const item = (key, issue) => {
    if (!items.has(key)) items.set(key, { key, issue, sessions: new Set(), open: new Set(), merged: new Set() })
    return items.get(key)
  }
  for (const s of x.c.workers) {
    const live = s.bucket !== 'completed' || x.recent(s.updatedAt)
    const found = [...x.c.matches.get(s.id).keys()].sort((a, b) => a - b)
    if (!found.length && live) item(`s:${s.id}`, null).sessions.add(s.id)
    for (const n of found) if (x.isOpen(n) || live) item(n, n).sessions.add(s.id)
  }
  const byPr = (p, set) => {
    const n = prIssue(p, x.isIssue)
    item(n ?? `p:${p.number}`, n)[set].add(p.number)
  }
  for (const p of snapshot.open_pulls || []) byPr(p, 'open')
  for (const p of (snapshot.pulls || []).filter((y) => x.recent(y.merged_at))) byPr(p, 'merged')
  for (const f of x.findings) if (f.issue && DISPATCHER_STEP.has(f.kind) && x.isOpen(f.issue)) item(f.issue, f.issue)
  owners(x, items, item)
  return [...items.values()]
}

/** The owner rules of every open issue (trackers left out); an issue that needs the owner, or is held, gets a row. */
function owners(x, items, item) {
  x.ownerOf = new Map()
  for (const i of x.c.issues.filter((y) => y.state === 'open' && x.kind(y.number) !== 'tracker')) {
    const sessions = [...(items.get(i.number)?.sessions || [])].map((id) => x.byId.get(id))
    const rules = ownerNeeded(x.raw.get(i.number) || i, x.c.loaded(i.number) || [], sessions, { owner: x.owner, url: x.url(i.number) })
    x.ownerOf.set(i.number, rules)
    const waits = x.kind(i.number) === 'ticket' && ['held', 'parked'].some((l) => i.labels.includes(l))
    if (rules.length || waits) item(i.number, i.number)
  }
}

/** Every row of the board, its group, and the facts around it. */
export function buildBoard(sessionsDoc, snapshot, options = {}) {
  const x = facts(sessionsDoc, snapshot, options)
  const rank = new Map(GROUPS.map(([g], k) => [g, k]))
  const rows = collect(x, snapshot).map((it) => row(it, x)).filter((r) => r.group)
    .sort((a, b) => rank.get(a.group) - rank.get(b.group) || (a.issue ?? 1e9) - (b.issue ?? 1e9) || String(a.key).localeCompare(String(b.key)))
  const open = x.c.issues.filter((i) => i.state === 'open')
  const tickets = open.filter((i) => x.kind(i.number) === 'ticket')
  const onBoard = new Set(rows.map((r) => r.issue))
  const merged = (snapshot.pulls || []).filter((p) => x.recent(p.merged_at)).sort((a, b) => String(a.merged_at).localeCompare(String(b.merged_at)))
  return {
    repo: x.repo,
    now: x.now,
    rows,
    openTickets: tickets.length,
    offBoard: tickets.filter((i) => !onBoard.has(i.number)).length,
    epics: open.filter((i) => x.kind(i.number) !== 'ticket').map((i) => ({ number: i.number, kind: x.kind(i.number), subs: x.raw.get(i.number)?.sub_issues_summary || null })).sort((a, b) => a.number - b.number),
    manual: manualTests(x.raw.get(MANUAL_TESTS), x.c.loaded(MANUAL_TESTS) || [], { owner: x.owner, url: x.url(MANUAL_TESTS) }),
    merged: merged.map((p) => ({ number: p.number, at: p.merged_at, issue: prIssue(p, x.isIssue) })),
    read: {
      at: sessionsDoc.read_at, source: sessionsDoc.source, pages: sessionsDoc.pages, total: sessionsDoc.read_total ?? sessionsDoc.sessions.length,
      inScope: x.c.sessions.length, openIssues: open.length, openPrs: (snapshot.open_pulls || []).length,
      notLoaded: rows.filter((r) => r.issue && x.isOpen(r.issue) && !x.c.loaded(r.issue)).map((r) => r.issue)
    },
    names: names(snapshot),
    issueNums: new Set(x.c.issues.map((i) => i.number))
  }
}

function prCell(p, pulls) {
  const info = pulls[p] || pulls[String(p)]
  if (!info) return { text: `{#${p}} open, checks not read`, next: ['Read its checks and Codex threads', 'dispatcher'] }
  const threads = info.codex_threads || 0
  const text = `{#${p}} open, checks ${code(info.checks || 'not read')}, ${plural(threads, 'open Codex thread', 'open Codex threads')}`
  if (info.checks === 'red') return { text, next: ['Fix the red checks', 'the session'] }
  if (threads > 0) return { text, next: [`Answer ${plural(threads, 'Codex thread', 'Codex threads')}`, 'the session'] }
  if (info.checks === 'pending') return { text, next: ['CI runs', 'CI'] }
  return { text, next: ['Opus judges the final head, then merge', 'Opus'] }
}

/** The facts of one row that decide its group. */
function rowFacts(it, x) {
  const n = it.issue
  const mine = x.findings.filter((f) => f.sessions.some((id) => it.sessions.has(id)) || (n !== null && f.issue === n))
  const open = n !== null && x.isOpen(n)
  return {
    n,
    open,
    mine,
    first: NEXT.map((k) => mine.find((f) => f.kind === k)).find(Boolean),
    sessions: [...it.sessions].map((id) => x.byId.get(id)).sort((a, b) => a.id.localeCompare(b.id)),
    prs: [...it.open].sort((a, b) => a - b).map((p) => prCell(p, x.pulls)),
    owner: open ? x.ownerOf.get(n) || [] : [],
    labels: n !== null ? labelsOf(x.raw.get(n) || {}) : [],
    closed: n !== null && !open && x.recent(x.raw.get(n)?.closed_at)
  }
}

/** The group of a row, first match wins, and its next step when the group decides it: [text, who]. */
function groupOf(it, f, x) {
  const has = (bucket) => f.sessions.some((s) => s.bucket === bucket)
  if (f.owner.length) {
    const how = f.owner[0].rule === 'needs-action' ? 'Answer the session' : 'Answer on the issue'
    return ['needs-you', [f.owner[0].words ? `Reply ${code(quote(f.owner[0].words, 40))}` : how, 'Shaked']]
  }
  if (f.mine.some((y) => y.kind === 'stuck')) return ['stuck']
  if (has('working')) return ['running']
  if (f.prs.length || has('review_ready')) return ['waiting']
  if (it.merged.size || f.closed) return ['done']
  if (f.first && DISPATCHER_STEP.has(f.first.kind)) return ['stuck']
  if (f.labels.includes('parked')) return ['held', ['Parked: waits until you pick it up', 'Shaked']]
  if (!f.labels.includes('held')) return [null]
  const deps = dependencies(x.raw.get(f.n)?.body || '').refs.filter(x.isOpen).sort((a, b) => a - b)
  return ['held', [deps.length ? `Starts after ${deps.map((d) => `{#${d}}`).join(', ')}` : 'Waits for the dispatcher to remove `held`', 'dispatcher']]
}

/** The next step when the group does not decide it: a janitor finding, else the group's default. */
function nextStep(group, f) {
  if (f.first) return [f.first.action, 'dispatcher']
  if (group === 'running') return ['Works on it', 'the session']
  if (group === 'waiting') return f.prs[0]?.next || ['Open the PR', 'the session']
  return f.open ? ['Close the issue after reading its HANDOFF', 'dispatcher'] : ['None', 'nobody']
}

function row(it, x) {
  const f = rowFacts(it, x)
  const [group, decided] = groupOf(it, f, x)
  if (!group) return {}
  const [next, who] = decided || nextStep(group, f)
  const merged = [...it.merged].sort((a, b) => a - b).map((p) => `{#${p}} merged`)
  return {
    key: it.key,
    issue: f.n,
    group,
    ticket: f.n === null ? 'no issue' : `{#${f.n}}${x.kind(f.n) === 'epic' ? ' (epic)' : ''}`,
    pr: [...f.prs.map((y) => y.text), ...merged].join('; ') || 'none',
    sessions: f.sessions,
    owner: f.owner,
    next,
    who
  }
}

/** 3 to 6 words for every issue and pull request in the snapshot, with no label or emoji inside. */
export function names(snapshot) {
  const out = new Map()
  // The task id prefix ("E407 task M9 (owner-only): ") and parentheses say nothing a reader needs.
  const clean = (t) => String(t || '').replace(/^(?:E\d+\s+)?(?:task\s+)?[A-Z]{1,2}-?\d+(?:\.\d+)?[a-z]?(?:\s*\([^)]*\))*\s*:\s*/i, '')
    .replace(/\([^)]*\)/g, '').replace(/#\d+/g, '').replace(/\p{Extended_Pictographic}/gu, '').replace(/\|/g, '/')
  for (const p of [...(snapshot.pulls || []), ...(snapshot.open_pulls || [])]) out.set(p.number, shortName({ title: clean(p.title) }))
  for (const i of snapshot.issues || []) out.set(i.number, shortName({ title: clean(i.title) }))
  return out
}

/** Replaces each {#n} with a link: "[#n words](url)" the first time, "[#n](url)" after. */
function linker(board) {
  const seen = new Set()
  return (text) => String(text).replace(/\{#(\d+)\}/g, (_, x) => {
    const n = Number(x)
    const where = `https://github.com/${board.repo}/${board.issueNums.has(n) ? 'issues' : 'pull'}/${n}`
    if (seen.has(n)) return `[#${n}](${where})`
    seen.add(n)
    return `[#${n} ${board.names.get(n) || 'not in the snapshot'}](${where})`
  })
}

const sessionCell = (r) => r.sessions.map((s) => `[session](${sessionUrl(s.id)}) ${code(STATE[s.bucket] || s.bucket || s.status)}`).join('; ') || 'none'
function ownerCell(r) {
  if (!r.owner.length) return 'no'
  const [o] = r.owner
  return `yes: ${code(quote(o.what, 80))}${o.words ? `, reply ${code(quote(o.words, 40))}` : ''}${r.owner.length > 1 ? `, and ${r.owner.length - 1} more` : ''}`
}
const time = (t) => new Date(typeof t === 'number' ? t : Date.parse(t)).toISOString().slice(0, 16).replace('T', ' ')
const or = (lines, list, empty) => (list.length ? lines : [empty])
const WHAT = { stuck: 'waits for the dispatcher', running: 'the session works on it', waiting: 'waits for CI or review' }

/** The fixed headings: TL;DR, What you need to do, Waiting for, Blocked on you, Done. */
function head(board) {
  const by = (g) => board.rows.filter((r) => r.group === g)
  const needs = by('needs-you')
  const counts = `${board.openTickets} open tickets, ${by('running').length + by('waiting').length} in progress, ${needs.length} need you`
  const steps = needs.map((r, k) => {
    const o = r.owner[0]
    return `${k + 1}. ${r.ticket}: ${code(quote(o.what, 60))}. ${o.words ? `Reply ${code(quote(o.words, 40))} [there](${o.url}).` : `Answer [there](${o.url}).`}`
  })
  const waiting = board.rows.filter((r) => WHAT[r.group])
    .map((r) => `- ${r.ticket}, ${r.sessions.length ? sessionCell({ sessions: r.sessions.slice(0, 2) }) : r.pr.split('; ')[0]}: ${WHAT[r.group]}. Expected: not known.`)
  const asks = needs.flatMap((r) => r.owner.map((o) => `- ${r.ticket}: ${OWNER_RULES.find(([k]) => k === o.rule)[1]} ([link](${o.url})).`))
  const done = board.merged.map((p) => `- {#${p.number}} merged ${time(p.at)} UTC${p.issue ? ` for {#${p.issue}}` : ''}, checked.`)
  return [
    '## TL;DR',
    `Board of ${time(board.now)} UTC: ${counts}, ${by('stuck').length} stuck, ${by('done').length} done since the last board (checked).`,
    needs.length ? `You need to do ${plural(needs.length, 'thing', 'things')} (below).` : 'Nothing needed from you.',
    '', '## What you need to do', ...or(steps, steps, 'Nothing.'),
    '', '## Waiting for', ...or(waiting, waiting, 'Nothing.'),
    '', '## Blocked on you', ...or(asks, asks, 'Nothing.'),
    '', '## Done', ...or(done, done, '- No pull request merged since the last board, checked.')
  ]
}

/** Details: one table per group, epics and trackers, manual tests, and what was read. */
function details(board) {
  const lines = ['## Details']
  for (const [g, title] of GROUPS) {
    const list = board.rows.filter((r) => r.group === g)
    const table = ['| Ticket | PR | Session | Owner needed? | Next step | Who |', '|---|---|---|---|---|---|',
      ...list.map((r) => `| ${r.ticket} | ${r.pr} | ${sessionCell(r)} | ${ownerCell(r)} | ${r.next} | ${r.who} |`)]
    lines.push(`### ${title}`, ...or(table, list, 'None.'), '')
  }
  const epics = board.epics.map((e) => {
    const subs = e.subs?.total ? `: ${e.subs.completed} of ${e.subs.total} sub-issues closed` : ''
    const manual = e.number === MANUAL_TESTS ? `: ${plural(board.manual.length, 'manual test', 'manual tests')} with no answer, optional, nothing waits` : ''
    return `- {#${e.number}} (${e.kind})${subs}${manual}.`
  })
  const manual = board.manual.map((t) => `- [${t.title}](${t.url}): no answer yet.`)
  const r = board.read
  lines.push('### Epics and trackers', ...or(epics, epics, 'None.'), '', '### Manual tests (optional, nothing waits)', ...or(manual, manual, 'None.'), '',
    '### What was read',
    `- Sessions: ${r.total} read on ${plural(r.pages, 'page', 'pages')} (${code(r.source)}) at ${time(r.at)} UTC, ${r.inScope} in scope, checked.`,
    `- GitHub: ${r.openIssues} open issues, ${r.openPrs} open PRs, checked. ${board.offBoard} open tickets have no session, PR or owner step: not listed.`)
  if (r.notLoaded.length) lines.push(`- Comments not loaded for ${r.notLoaded.length} rows: ${r.notLoaded.map((n) => `{#${n}}`).join(', ')}; their owner rules are not checked.`)
  return lines
}

/** The board text in the status-board template. */
export function formatBoard(board) {
  return [...head(board), '', ...details(board)].map(linker(board)).join('\n') + '\n'
}

/** Issues whose comments the board needs, and open PRs whose checks it needs. */
export function boardNeeds(sessionsDoc, snapshot, { comments = {}, pulls = {}, today, since } = {}) {
  const board = buildBoard(sessionsDoc, snapshot, { comments, pulls, today, since })
  const c = context(sessionsDoc, snapshot, comments)
  const markers = snapshot.markers || {}
  const want = new Set([...sessionNeeds(sessionsDoc, snapshot, comments).issues, ...(markers.release || []), ...(markers.question || [])])
  for (const r of board.rows) if (r.issue) want.add(r.issue)
  for (const i of c.issues.filter((x) => x.state === 'open')) {
    if (i.labels.some((l) => ['owner', 'held', 'epic'].includes(l)) || i.number === MANUAL_TESTS) want.add(i.number)
  }
  const issues = [...want].filter((n) => c.byNum.get(n)?.state === 'open' && !c.loaded(n)).sort((a, b) => a - b)
  const prs = (snapshot.open_pulls || []).map((p) => p.number).filter((p) => !(pulls[p] || pulls[String(p)])).sort((a, b) => a - b)
  return { issues, prs }
}

/** The janitor snapshot plus markers.question. `run` is injectable for tests. */
export function fetchBoardSnapshot({ repo = REPO, run = (args) => execFileSync('gh', args, { encoding: 'utf8', maxBuffer: 64 << 20 }) } = {}) {
  const snapshot = fetchSnapshot({ repo, run })
  const q = `repo:${repo} is:issue is:open "question for you" in:comments`
  const text = run(['api', '-X', 'GET', 'search/issues', '-f', `q=${q}`, '-f', 'per_page=100', '--paginate', '--jq', '.items[].number'])
  snapshot.markers.question = text.split('\n').filter(Boolean).map(Number)
  return snapshot
}

function main() {
  const [cmd, sessionsFile, snapshotFile, ...rest] = process.argv.slice(2)
  if (cmd === 'fetch') {
    process.stdout.write(JSON.stringify(fetchBoardSnapshot(), null, 1) + '\n')
    return
  }
  const opt = (name) => { const k = rest.indexOf(name); return k === -1 ? null : rest[k + 1] }
  const json = (f) => (f ? JSON.parse(readFileSync(f, 'utf8')) : {})
  if (!['need', 'board'].includes(cmd) || !sessionsFile || !snapshotFile) {
    console.error('usage: status-board.mjs fetch | need|board sessions.json snapshot.json [--comments f] [--pulls f] [--today ISO] [--since ISO]')
    process.exit(2)
  }
  const doc = json(sessionsFile)
  const errors = validateSessions(doc)
  if (errors.length) {
    console.error(errors.join('\n'))
    process.exit(1)
  }
  for (const name of ['--today', '--since']) {
    if (opt(name) && Number.isNaN(Date.parse(opt(name)))) {
      console.error(`${name} must be an ISO time`)
      process.exit(2)
    }
  }
  const options = { comments: json(opt('--comments')), pulls: json(opt('--pulls')), today: opt('--today') || doc.read_at, since: opt('--since') }
  const snapshot = json(snapshotFile)
  if (cmd === 'need') {
    const n = boardNeeds(doc, snapshot, options)
    console.log(`Load comments for ${n.issues.length} issues: ${n.issues.map((x) => `#${x}`).join(' ') || 'none'}`)
    console.log(`Read checks and Codex threads for ${n.prs.length} open PRs: ${n.prs.map((x) => `#${x}`).join(' ') || 'none'}`)
    return
  }
  process.stdout.write(formatBoard(buildBoard(doc, snapshot, options)))
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main()
}
